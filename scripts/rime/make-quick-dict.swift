#!/usr/bin/env swift
// Builds the RIME Quick (速成) dictionary quick5.dict.yaml from libcangjie's data/table.txt
// (Public Domain; see ime/rime/LICENSE-data.txt).
//
// Usage: swift scripts/rime/make-quick-dict.swift <table.txt> <output quick5.dict.yaml>
//
// Selection and ordering rules are identical to scripts/make-quick-table.swift (keep the two in line):
// Chinese characters in Big5; Quick code = first + last letter of a Cangjie 5 code (Cangjie 3 when the
// Cangjie 5 column is NA); a one-letter code stays as it is. One row per (code, character); under one code
// the higher ordering comes first, ties keep the file order.
// Output: RIME dictionary, `character<TAB>code` per line, grouped by code.
import Foundation

func quickCode(_ cangjie: Substring) -> String? {
    guard !cangjie.isEmpty, cangjie.utf8.allSatisfy({ $0 >= 97 && $0 <= 122 }) else { return nil }
    guard cangjie.count > 1, let first = cangjie.first, let last = cangjie.last else { return String(cangjie) }
    return String([first, last])
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write(Data("usage: make-quick-dict.swift <table.txt> <output>\n".utf8))
    exit(2)
}
let text = try String(contentsOfFile: arguments[1], encoding: .utf8)

struct Row { let code: String; let character: String; let order: Int; let index: Int }
var rows: [Row] = []
var seen = Set<String>()
var index = 0
for line in text.split(separator: "\n") where !line.hasPrefix("#") {
    let columns = line.split(separator: " ", omittingEmptySubsequences: true)
    guard columns.count == 15 else {
        FileHandle.standardError.write(Data("unexpected column count \(columns.count): \(line)\n".utf8))
        exit(1)
    }
    guard columns[2] == "1", columns[3] == "1" else { continue }
    let cangjie = columns[12] != "NA" ? columns[12] : columns[11]
    let order = Int(columns[14]) ?? 0
    for code in cangjie.split(separator: ",") {
        guard let quick = quickCode(code) else { continue }
        let key = quick + "\t" + columns[0]
        if seen.insert(key).inserted {
            rows.append(Row(code: quick, character: String(columns[0]), order: order, index: index))
            index += 1
        }
    }
}
rows.sort { a, b in
    if a.code != b.code { return a.code < b.code }
    if a.order != b.order { return a.order > b.order }
    return a.index < b.index
}
let header = """
# quick5.dict.yaml (Remote Keyboard, Quick input method dictionary)
#
# Derived from the Cangjie table of libcangjie (Public Domain):
#   https://gitlab.freedesktop.org/cangjie/libcangjie/-/raw/main/data/table.txt
# Generated by scripts/rime/make-quick-dict.swift; do not edit by hand. See LICENSE-data.txt.
---
name: quick5
version: "2026.11.20"
sort: original
...

"""
let body = rows.map { "\($0.character)\t\($0.code)" }.joined(separator: "\n") + "\n"
try (header + body).write(toFile: arguments[2], atomically: true, encoding: .utf8)
print("rows: \(rows.count)")
