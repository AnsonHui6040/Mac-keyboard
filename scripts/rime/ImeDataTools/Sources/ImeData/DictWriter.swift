import Foundation

public struct DictEntry: Equatable, Sendable {
    public var text: String
    public var code: String
    public var weight: Int?

    public init(text: String, code: String, weight: Int?) {
        self.text = text
        self.code = code
        self.weight = weight
    }
}

public enum DictWriter {
    public static let version = "2026.11.20"

    /// A RIME `*.dict.yaml`: comment header, YAML header, then `text<TAB>code[<TAB>weight]` lines.
    public static func render(name: String, sort: String, sources: [String], entries: [DictEntry]) -> String {
        var out = "# \(name).dict.yaml (Remote Keyboard)\n#\n"
        for source in sources { out += "# \(source)\n" }
        out += "# Generated by scripts/rime/make-dicts.sh; do not edit by hand. See LICENSE-data.txt.\n"
        out += "---\nname: \(name)\nversion: \"\(version)\"\nsort: \(sort)\n...\n\n"
        for entry in entries {
            out += "\(entry.text)\t\(entry.code)"
            if let weight = entry.weight { out += "\t\(weight)" }
            out += "\n"
        }
        return out
    }
}
